local json=require('luci.jsonc')
local parser=dofile(arg[1]..'/rootfiles/usr/share/privacy-access/proxy-subscription.lua')
local n=parser.parse('anytls://test-secret@example.com:443/?sni=example.com#HK%2001','HK')
assert(#n==1 and n[1].tag=='HK 01' and n[1].tls.insecure==false and n[1].routing_mark==201)
local n2=parser.parse('proxies:\n  - name: Test\n    type: anytls\n    server: example.com\n    port: 443\n    password: dummy\n    skip-cert-verify: true\n','')
assert(#n2==1 and n2[1].tls.insecure==true)
local native=json.stringify({outbounds={{type='trojan',tag='safe',server='example.com',server_port=443,password='dummy',
    tls={enabled=true,certificate_path='/etc/shadow'},detour='direct',bind_interface='usb0'}},inbounds={{listen='0.0.0.0'}},route={final='direct'}})
local n3=parser.parse(native,'')
assert(n3[1].tls.certificate_path==nil and n3[1].detour==nil and n3[1].bind_interface==nil)
local duplicate=parser.parse('trojan://dummy@example.com:443#Same\ntrojan://dummy@example.org:443#Same','')
assert(#duplicate==2 and duplicate[1].tag~=duplicate[2].tag)
local encoded=require('nixio').bin.b64encode('vless://00000000-0000-0000-0000-000000000001@example.com:443?security=tls&sni=example.com#Test')
assert(parser.parse(encoded,'')[1].type=='vless')
assert(not pcall(parser.parse,'{"outbounds":[{"type":"direct","tag":"bad"}]}',''))
assert(not pcall(parser.parse,'anytls://dummy@example.com:443#US','香港|HK'))
assert(not pcall(parser.parse,'ss://YWVzLTI1Ni1nY206cHdk@example.com:443?plugin=unknown#Plugin',''))
print('PASS subscription: URI/Base64, Clash YAML, native JSON allow-list, safe TLS defaults, filtering, unique names, and reject empty/unsupported data.')
